// Local stdio MCP proxy. It never launches a provider or reads provider credentials.
const target = new URL(process.env.KIVUNO_MCP_URL || 'http://127.0.0.1/invalid');
if (
  target.protocol !== 'http:' ||
  target.hostname !== '127.0.0.1' ||
  target.pathname !== '/api/external-agent/rpc' ||
  target.search ||
  target.hash ||
  target.username ||
  target.password ||
  !target.port
)
  throw new Error('Use the local MCP configuration generated by Kivuno.');
const token = process.env.KIVUNO_MCP_TOKEN;
if (!/^[A-Za-z0-9_-]{43}$/.test(token || ''))
  throw new Error('Missing scoped Kivuno connection token.');
let pending = 0;
let stopping = false;
const send = (value) => process.stdout.write(JSON.stringify(value) + '\n');
async function forward(message) {
  if (++pending > 16) {
    pending--;
    throw new Error('Too many pending requests.');
  }
  try {
    const response = await fetch(target, {
      method: 'POST',
      redirect: 'error',
      signal: AbortSignal.timeout(90000),
      headers: { Authorization: `Bearer ${token}`, 'Content-Type': 'application/json' },
      body: JSON.stringify(message),
    });
    if (!response.ok)
      throw new Error(
        response.status === 401
          ? 'Kivuno connection expired. Reconnect in Team.'
          : `Kivuno request failed (${response.status}).`,
      );
    return response.status === 202 ? null : await response.json();
  } finally {
    pending--;
  }
}
const heartbeat = setInterval(() => {
  if (!stopping)
    void forward({ jsonrpc: '2.0', id: 'kivuno-heartbeat', method: 'ping' }).catch(() => {});
}, 15000);
heartbeat.unref();
function receive(line) {
  let message;
  try {
    message = JSON.parse(line);
  } catch {
    send({ jsonrpc: '2.0', id: null, error: { code: -32700, message: 'Invalid JSON.' } });
    return;
  }
  if (!message || typeof message !== 'object' || Array.isArray(message)) {
    send({
      jsonrpc: '2.0',
      id: null,
      error: { code: -32600, message: 'Expected a JSON-RPC object.' },
    });
    return;
  }
  void forward(message)
    .then((result) => {
      if (result) send(result);
    })
    .catch((error) => {
      if (message.id !== undefined)
        send({ jsonrpc: '2.0', id: message.id, error: { code: -32000, message: error.message } });
    });
}
let buffer = '';
process.stdin.setEncoding('utf8');
process.stdin.on('data', (chunk) => {
  buffer += chunk;
  for (;;) {
    const end = buffer.indexOf('\n');
    if (end < 0) break;
    const line = buffer.slice(0, end);
    buffer = buffer.slice(end + 1);
    if (Buffer.byteLength(line) > 128 * 1024) {
      process.stderr.write('MCP frame limit exceeded.\n');
      process.exit(1);
    }
    if (line.trim()) receive(line);
  }
  if (Buffer.byteLength(buffer) > 128 * 1024) {
    process.stderr.write('MCP frame limit exceeded.\n');
    process.exit(1);
  }
});
process.stdin.on('end', () => {
  stopping = true;
  clearInterval(heartbeat);
});
